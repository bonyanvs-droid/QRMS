/**
 * Plan-Target Surgical Correction — preserves plan history.
 * -------------------------------------------------------------
 * For every active/at_risk plan whose stored target was polluted by the
 * stage-key precedence bug (fixed in be029e0), this script:
 *   1. Re-routes the plan's targetEnd to the student's own GRADE target via
 *      applyTeacherOverride — which rebuilds only future days, records a
 *      TeacherOverride entry, and bumps planVersion (full audit trail).
 *   2. Corrects the originalTarget snapshot fields (targetEnd/displayTarget/
 *      totalUnits/totalAyahs) — the snapshot was generated by the bug.
 *   3. Resets status to 'active' and clears the stale at_risk diagnostic;
 *      the next recorded achievement re-evaluates risk on the full-year
 *      horizon honestly.
 *   4. Appends a recalculationHistory audit note documenting the correction.
 *
 * Past days and all recorded achievements are never touched.
 *
 * Usage:
 *   DATABASE_URL=postgres://... npx tsx scripts/repairPlanTargets.ts          # dry-run
 *   DATABASE_URL=postgres://... npx tsx scripts/repairPlanTargets.ts --apply  # write
 */
import '../server/config/env';
import { getDbPool } from '../server/config/db';
import { BundledQuranProvider } from '../src/quran/providers/BundledQuranProvider';
import { PlanRecalculationService } from '../src/quran/services/recalculationService';
import { RangeCalculator } from '../src/quran/services/rangeCalculator';
import { resolveQuranPlanConfiguration } from '../src/quran/services/studentPlanBridge';
import { findStageConfigForStudent } from '../src/quran/models/stageConfig';
import { syncAcademicConfigWithActiveTerm } from '../src/lib/academicYearUtils';
import { getSurahArabicName, formatQuranRange } from '../src/quran/utils/positionFormatter';

const APPLY = process.argv.includes('--apply');
const camelize = (v: any): any =>
  Array.isArray(v)
    ? v.map(camelize)
    : v && typeof v === 'object' && !(v instanceof Date)
      ? Object.fromEntries(
          Object.entries(v).map(([k, val]) => [
            k.replace(/_([a-z])/g, (_m, c) => c.toUpperCase()),
            camelize(val),
          ])
        )
      : v;

async function main() {
  const pool = getDbPool();
  if (!pool) {
    console.error('DATABASE_URL is not configured.');
    process.exit(1);
  }
  const provider = new BundledQuranProvider();
  const surahs = await provider.getSurahs();
  const recalc = new PlanRecalculationService(provider);
  const rangeCalc = new RangeCalculator(provider);

  const ayRow = (await pool.query(`SELECT * FROM academic_years LIMIT 1`)).rows[0];
  const academicConfig = syncAcademicConfigWithActiveTerm(camelize(ayRow));
  const stageConfigs = (await pool.query(`SELECT * FROM quran_stage_configs`)).rows.map(camelize);
  const stages = (await pool.query(`SELECT * FROM stages`)).rows.map(camelize);
  const halaqahs = (await pool.query(`SELECT * FROM halaqahs`)).rows.map(camelize);
  const tenants = (await pool.query(`SELECT * FROM tenants`)).rows.map(camelize);
  const students = new Map(
    (await pool.query(`SELECT * FROM students WHERE is_active AND NOT is_archived`)).rows
      .map(camelize)
      .map((s) => [s.id, s])
  );
  const plans = (
    await pool.query(
      `SELECT id, student_id, status, plan_data FROM quran_plans
       WHERE status IN ('active','at_risk') ORDER BY created_at`
    )
  ).rows;

  const now = new Date();
  const todayIso = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(
    now.getDate()
  ).padStart(2, '0')}`;
  const nowIso = now.toISOString();

  console.log(`\n===== تصحيح مستهدفات الخطط — ${APPLY ? 'تنفيذ' : 'جاف (بدون كتابة)'} =====\n`);
  let fixed = 0;
  let skipped = 0;

  for (const row of plans) {
    const plan = row.plan_data;
    const student = students.get(row.student_id) as any;
    const stored = plan?.targetEnd;
    if (!student || !stored || plan?.targetSource === 'explicit') {
      skipped++;
      continue;
    }

    const stageConfig = findStageConfigForStudent(student, stageConfigs);
    const resolved = resolveQuranPlanConfiguration(
      {
        student,
        stageConfig,
        allStageConfigs: stageConfigs,
        academicConfig,
        halaqah: halaqahs.find((h) => h.id === student.halaqahId),
        stages,
        tenant: tenants.find((t) => t.id === student.tenantId),
      } as any,
      surahs
    );
    const want = resolved.targetEnd;
    const same =
      stored.surahNumber === want.surahNumber && stored.ayahNumber === want.ayahNumber;
    if (same) {
      skipped++;
      continue;
    }

    const storedLabel = `${getSurahArabicName(stored.surahNumber)}:${stored.ayahNumber}`;
    const wantLabel = `${getSurahArabicName(want.surahNumber)}:${want.ayahNumber}`;
    console.log(`✘ ${student.fullName} (${student.grade}) [${row.status}]: ${storedLabel} → ${wantLabel}`);

    if (!APPLY) {
      fixed++;
      continue;
    }

    try {
      // 1. Route the plan to the corrected target — rebuilds future days only,
      //    records TeacherOverride + bumps planVersion.
      const rebuilt = await recalc.applyTeacherOverride({
        plan,
        teacherId: 'system_target_fix',
        teacherName: 'تصحيح المستهدف (النظام)',
        effectiveFromDate: todayIso,
        reason: 'custom',
        reasonArabicText: `تصحيح مستهدف الخطة: ${storedLabel} ← ${wantLabel} (أولوية مستهدف الصف على المرحلة)`,
        newTargetEnd: { surahNumber: want.surahNumber, ayahNumber: want.ayahNumber },
      });

      // 2. Correct the bug-generated originalTarget snapshot fields.
      const correctedUnits =
        await rangeCalc.partitionSurahsWithCumulativePaceAndConsolidation(
          rebuilt.targetStart,
          want,
          rebuilt.unitType,
          rebuilt.dailyAmount,
          rebuilt.direction,
          rebuilt.consolidationDaysPerSurah ?? 3,
          rebuilt.revisionDailyPages ?? 1,
          [],
          rebuilt.revisionDirection || 'backward',
          rebuilt.revisionSettings?.unitType || 'page',
          rebuilt.revisionSettings?.surahsPerDay,
          rebuilt.autoMinorRevisionMode !== false
        );
      const correctedAyahs = await provider.getAyahsInRange(
        rebuilt.targetStart,
        want,
        rebuilt.direction
      );
      rebuilt.originalTarget = {
        ...rebuilt.originalTarget,
        targetEnd: { surahNumber: want.surahNumber, ayahNumber: want.ayahNumber },
        totalUnits: correctedUnits.length,
        totalAyahs: correctedAyahs.length,
        displayTarget: formatQuranRange(rebuilt.targetStart, want, { includeSurahWord: true }),
      };

      // 3. Clear the stale at_risk state — next recalc re-evaluates honestly
      //    on the full-year horizon.
      rebuilt.status = 'active';
      rebuilt.targetAtRiskDiagnostic = undefined;

      // 4. Audit trail inside the plan document itself.
      rebuilt.recalculationHistory = [
        {
          id: `targetfix_${Date.now()}`,
          timestamp: nowIso,
          trigger: 'schedule_change',
          effectiveFromDate: todayIso,
          previousRemainingUnits: rebuilt.recalculationHistory?.[0]?.newRemainingUnits ?? 0,
          newRemainingUnits: correctedUnits.length,
          targetAtRisk: false,
          notes: `تصحيح آلي للمستهدف: كان مسجلاً «${storedLabel}» (مستهدف المرحلة بسبب خلل أولوية المفاتيح) وصُحّح إلى «${wantLabel}» (مستهدف ${student.grade}). السجل التاريخي محفوظ بالكامل.`,
        },
        ...(rebuilt.recalculationHistory || []),
      ];
      rebuilt.updatedAt = nowIso;

      await pool.query(
        `UPDATE quran_plans SET plan_data = $1::jsonb, status = $2, updated_at = NOW() WHERE id = $3`,
        [JSON.stringify(rebuilt), rebuilt.status, row.id]
      );
      fixed++;
      console.log(`   ✔ صُحّحت الخطة ${row.id}`);
    } catch (e: any) {
      console.log(`   ✘ فشل التصحيح: ${e?.message}`);
    }
  }

  console.log(`\n===== ${fixed} خطة ${APPLY ? 'صُحّحت' : 'ستُصحَّح'} / ${skipped} سليمة أو مستثناة =====\n`);
  process.exit(0);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
